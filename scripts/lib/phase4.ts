export interface LemmaCandidate {
  rank: number;
  lemma: string;
  class: 'content' | 'function';
  pos_label: string;
  wn_pos: 'n' | 'v' | 'a' | 'r' | null;
  in_cmu: boolean;
}

export interface GeneratedGloss {
  rank: number;
  headword: string;
  normalized: string;
  has_wordnet: boolean;
  is_valid_headword: boolean;
  ok: boolean;
  pos?: string;
  pronunciation_deva?: string;
  definition_en?: string;
  meaning_hi?: string;
}

export function toPhase4Entry(gloss: GeneratedGloss): {
  headword: string; normalized: string; pos: string; pronunciation_deva: string; definition_en: string; meaning_hi: string;
  source: string; license_attribution: string; reviewed: 0;
} | null {
  if (!gloss.ok || !gloss.is_valid_headword || !gloss.pos || !gloss.pronunciation_deva || !gloss.definition_en || !gloss.meaning_hi) return null;
  const hasWordNet = gloss.has_wordnet;
  return {
    headword: gloss.headword,
    normalized: gloss.normalized,
    pos: gloss.pos,
    pronunciation_deva: gloss.pronunciation_deva,
    definition_en: gloss.definition_en,
    meaning_hi: gloss.meaning_hi,
    source: hasWordNet ? 'Panna machine-assisted from Princeton WordNet 3.1' : 'Panna machine-generated',
    license_attribution: hasWordNet
      ? (gloss.rank <= 5000 ? 'Definition: Princeton WordNet 3.1; Hindi: machine-assisted, native review pending'
        : 'Definition: Princeton WordNet 3.1; Hindi: machine-generated, not yet reviewed')
      : 'English and Hindi glosses: machine-generated by Panna; not yet human-reviewed',
    reviewed: 0,
  };
}

/** Content candidates in deterministic rank order, excluding words supplied by editorial layers. */
export function selectPhase4Candidates(lemmas: LemmaCandidate[], reserved: Set<string>): LemmaCandidate[] {
  return lemmas.filter((item) => item.class === 'content' && !reserved.has(item.lemma))
    .sort((a, b) => a.rank - b.rank || a.lemma.localeCompare(b.lemma));
}

export function generatedEntriesNeeded(targetEntries: number, existingEntries: number): number {
  return Math.max(0, targetEntries - existingEntries);
}
